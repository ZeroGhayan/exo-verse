uint16_t exo_elem_mul(ExoElem atk, ExoElem def)
{
	if ((unsigned)atk >= EXO_ELEM_COUNT || (unsigned)def >= EXO_ELEM_COUNT)
		return 100;
	return CHART[atk][def];
}

uint16_t exo_elem_mul2(ExoElem atk, ExoElem def1, ExoElem def2)
{
	uint16_t a = exo_elem_mul(atk, def1);
	uint16_t b;

	if (def2 == def1)
		return a;
	b = exo_elem_mul(atk, def2);
	return (uint16_t)((unsigned)a * (unsigned)b / 100u);
}

const char *exo_elem_name(ExoElem e)
{
	if ((unsigned)e >= EXO_ELEM_COUNT)
		return "?";
	return NAMES[e];
}

ExoElem exo_elem_next(ExoElem e)
{
	return (ExoElem)(((unsigned)e + 1u) % (unsigned)EXO_ELEM_COUNT);
}